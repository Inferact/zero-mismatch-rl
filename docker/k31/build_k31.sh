#!/bin/bash
# Build stage of the K31 preview image (the Dockerfile and the enroot dev-image job both run this file, in a fresh
# directory): compiles only the nine K31 CMake targets of the vLLM delivery tree and the mLite wheel, and stages the
# vLLM files the delivery branch changed. Every other vLLM file, binaries included, stays the base image's.
#   build_k31.sh <vLLM tree> <mLite tree (experimental/lite)> <out dir> <changes> <base files> <vLLM version>
#                <vLLM commit> <Megatron-LM tree holding megatron/core>
#   The Megatron-LM tree is the mLite branch's own Megatron-LM commit (the mLite actor imports megatron.core
#   for pipeline parallelism); its megatron/core is staged for install_k31.sh next to megatron.lite.
#   <changes>:    git diff --no-renames --name-status <base commit> <vLLM head>  (the whole tree)
#   <base files>: git ls-tree -r --name-only <base commit> -- vllm
# Out: <out>/stage/vllm/... (K31 modules + changed files + _version.py), <out>/stage/DELETED, <out>/stage/SOURCE.sha256
# (every file of <vLLM tree>/vllm, for install_k31.sh), <out>/dist/<mLite wheel>, <out>/mcore/megatron/core, <out>/build.
# Refuses a branch that changes anything the overlay cannot carry (outside vllm/, csrc/k31/, tests/, the CMake and
# setup.py registration), and a changes list that disagrees with what the trees show: the files that differ from the
# base install (A/M) and the base commit's files missing from the head (D). Only such tracked files are deleted.
# External CMake sources come from FetchContent, or from the *_SRC_DIR variables vLLM's CMake reads when set.
set -euo pipefail
trap 'echo "${BASH_SOURCE[0]##*/} failed at line ${LINENO}" >&2' ERR
SRC=$1 MLITE=$2 OUT=$3 CHANGES=$4 BASE_FILES=$5 VERSION=$6 COMMIT=$7 MCORE=$8
TARGETS=(_k31_tree_C _k31_tp_ordered_C _k31_lin_lora_C _k31_moe_lora_fuse_C _k31_moe_lora_mma_C _k31_bi_gemm_C
  _k31_kda_pf4_C _k31_kda_dsync8_C _k31_kda_v6_C)
cd /
[[ ! -e "${OUT}" ]] || { echo "${OUT} exists: build in a fresh directory"; exit 1; }
mkdir -p "${OUT}/build" "${OUT}/stage" "${OUT}/dist"
VP=$(python3 -c 'import importlib.util, os; print(os.path.dirname(importlib.util.find_spec("vllm").origin))')

# what the overlay carries: vllm/ files, plus the K31 kernels and their registration (compiled below)
outside=$(cut -f2 "${CHANGES}" | grep -vE '^(vllm/|csrc/k31/|tests/|CMakeLists\.txt$|setup\.py$)' || true)
[[ -z "${outside}" ]] || { echo "branch changes the overlay would drop: ${outside}"; exit 1; }
(cd "${SRC}" && find vllm -type f -print0 | sort -z | xargs -0 sha256sum) >"${OUT}/stage/SOURCE.sha256"
listed=$(awk -F'\t' '$1 ~ /^[AM]$/ && $2 ~ /^vllm\// {print $2}' "${CHANGES}" | sort)
differ=$(cd "${SRC}" && find vllm -type f | sort | while read -r f; do
  cmp -s "${f}" "${VP}/${f#vllm/}" || echo "${f}"; done)
[[ "${listed}" == "${differ}" ]] || {
  echo "changes list and base install disagree:"; diff <(echo "${listed}") <(echo "${differ}") || true; exit 1; }
listed_d=$(awk -F'\t' '$1 == "D" && $2 ~ /^vllm\// {print $2}' "${CHANGES}" | sort)
gone=$(comm -23 <(sort "${BASE_FILES}") <(cd "${SRC}" && find vllm -type f | sort))
[[ "${listed_d}" == "${gone}" ]] || {
  echo "changes list and base/head trees disagree on deletions:"; diff <(echo "${listed_d}") <(echo "${gone}") || true
  exit 1; }
other=$(awk -F'\t' '$2 ~ /^vllm\// && $1 !~ /^[AMD]$/' "${CHANGES}")
[[ -z "${other}" ]] || { echo "unexpected change: ${other}"; exit 1; }
for path in ${differ}; do install -D -m 644 "${SRC}/${path}" "${OUT}/stage/${path}"; done
: >"${OUT}/stage/DELETED"
for path in ${gone}; do
  [[ -f "${VP}/${path#vllm/}" ]] || { echo "${path}: tracked at the base commit but not in the base install"; exit 1; }
  echo "${path}" >>"${OUT}/stage/DELETED"
done
# vllm.__version__ of the overlay (the base's is a dev version of the commit it was built from); install_k31.sh
# gives the dist-info the same version
python3 - "${VERSION}" "${COMMIT}" "${OUT}/stage/vllm/_version.py" <<'PY'
import sys

version, commit, out = sys.argv[1:]
release, _, local = version.partition("+")
parts = tuple(int(x) for x in release.split(".")) + ((local,) if local else ())
assert len(commit) == 40 and all(c in "0123456789abcdef" for c in commit), commit
lines = [
    "# generated by build_k31.sh (K31 overlay of the base image's vLLM)",
    "from __future__ import annotations",
    "",
    '__all__ = ["__version__", "__version_tuple__", "version", "version_tuple", "__commit_id__", "commit_id"]',
    "",
    f"__version__ = version = {version!r}",
    f"__version_tuple__ = version_tuple = {parts!r}",
    "",
    f"__commit_id__ = commit_id = {'g' + commit[:12]!r}",
]
with open(out, "w") as f:
    f.write("\n".join(lines) + "\n")
PY

export PATH=/usr/local/cuda/bin:${PATH}
# torch's CUDA headers include the cuSPARSE/cuBLAS/cuSOLVER headers; the runtime image has the libraries only
CV=$(nvcc --version | sed -n 's/.*release \([0-9]*\)\.\([0-9]*\).*/\1-\2/p')
if [[ ! -f /usr/local/cuda/include/cusparse.h ]]; then
  apt-get update -qq && DEBIAN_FRONTEND=noninteractive apt-get install -y -qq --no-install-recommends \
    "libcusparse-dev-${CV}" "libcublas-dev-${CV}" "libcusolver-dev-${CV}" >/dev/null
fi
python3 -m pip install -q --no-cache-dir "cmake==3.31.6"
# the configure call of vLLM's setup.py (cmake_build_ext.configure), without a compiler launcher
cmake -S "${SRC}" -B "${OUT}/build" -DCMAKE_BUILD_TYPE=Release -DVLLM_TARGET_DEVICE=cuda \
  -DVLLM_PYTHON_EXECUTABLE="$(command -v python3)" \
  -DVLLM_PYTHON_PATH="$(python3 -c 'import sys; print(":".join(sys.path))')" \
  -DFETCHCONTENT_BASE_DIR="${SRC}/.deps" -DNVCC_THREADS="${NVCC_THREADS:-2}" \
  -DCMAKE_CUDA_COMPILER=/usr/local/cuda/bin/nvcc >"${OUT}/configure.log" 2>&1 \
  || { tail -40 "${OUT}/configure.log"; exit 1; }
cmake --build "${OUT}/build" -j "${MAX_JOBS:-64}" "${TARGETS[@]/#/--target=}" >"${OUT}/build.log" 2>&1 \
  || { grep -n -B3 -A20 -m3 -E 'error' "${OUT}/build.log" | tail -60; exit 1; }
for t in "${TARGETS[@]}"; do
  cmake --install "${OUT}/build" --prefix "${OUT}/stage" --component "${t}" >/dev/null
done
suffix=$(python3 -c 'import sysconfig; print(sysconfig.get_config_var("EXT_SUFFIX"))')
for t in "${TARGETS[@]}"; do
  [[ -f "${OUT}/stage/vllm/${t}${suffix}" ]] || { echo "no ${t}${suffix}: CUDA_ARCHS has no 10.x entry?"; exit 1; }
done
python3 -m pip wheel -q --no-cache-dir --no-build-isolation --no-deps -w "${OUT}/dist" "${MLITE}"
tag=$(python3 -c 'import sys; print("cp%d%d" % sys.version_info[:2])')
ls "${OUT}/dist"/nemotron_megatron_lite-*-"${tag}-${tag}"-linux_*.whl
[[ -f "${MCORE}/megatron/core/__init__.py" ]] || { echo "no megatron/core in ${MCORE}"; exit 1; }
mkdir -p "${OUT}/mcore/megatron"
(cd "${MCORE}/megatron" && find core -type f -not -path '*/__pycache__/*' -print0 | sort -z \
  | tar -c --null -T -) | tar -x -C "${OUT}/mcore/megatron"
echo "BUILD_K31_OK $(find "${OUT}/stage/vllm" -type f | wc -l) staged files, megatron.core $(find "${OUT}/mcore" -type f 2>/dev/null | wc -l) files"
